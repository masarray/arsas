        Assert.Contains("PLANNED SIGNALS 1", text, StringComparison.Ordinal);
        Assert.Contains("NOT STARTED", text, StringComparison.Ordinal);
        Assert.DoesNotContain("PASS 0", text, StringComparison.Ordinal);
        Assert.DoesNotContain("PENDING 1", text, StringComparison.Ordinal);
        Assert.DoesNotContain("Testing is incomplete", text, StringComparison.Ordinal);
        Assert.DoesNotContain("CUSTOMER FAT RECORD", text, StringComparison.Ordinal);
        Assert.Contains("ADD/GGIO6.CBOpnd", text, StringComparison.Ordinal);
        Assert.Contains("APPENDIX A - PLANNED IEC 61850 IFAT CHECKS", text, StringComparison.Ordinal);
        Assert.Contains("CUSTOMER REVIEWER", text, StringComparison.Ordinal);
        Assert.Contains("Auto-generated by ARSAS IEC 61850 Protocol Tester", text, StringComparison.Ordinal);
        Assert.Contains("To be completed during IFAT", text, StringComparison.Ordinal);
    }

    [Fact]
    public void ExecutivePdf_StartedButIncompleteScopeBecomesPartialTestRecord()
    {
        var project = BuildProject("IFAT EXECUTION", "Operated", "Normal");
        Start(project.Ieds[0].TestPoints[0]);

        var text = Encoding.ASCII.GetString(IoFatPdfReportService.Generate(project));

        Assert.Contains("PARTIAL", text, StringComparison.Ordinal);
        Assert.Contains("NOT FOR CUSTOMER ACCEPTANCE", text, StringComparison.Ordinal);
        Assert.Contains("APPENDIX A - DETAILED IEC 61850 SIGNAL EVIDENCE", text, StringComparison.Ordinal);
        Assert.DoesNotContain("BLANK IFAT TEST FORM", text, StringComparison.Ordinal);
    }

