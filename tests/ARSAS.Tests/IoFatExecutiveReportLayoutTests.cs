    private static void Complete(IoTestPointPlan point)
    {
        var evaluator = new IoTestTransitionEvaluator();
        evaluator.StartAttempt(point, Observation(false, 1));
        evaluator.Observe(point, Observation(true, 2));
        evaluator.Observe(point, Observation(false, 3));
    }

    private static void Start(IoTestPointPlan point)
    {
        new IoTestTransitionEvaluator().StartAttempt(point, Observation(false, 1));
    }

    private static IoTestObservation Observation(bool state, long sequence)
    {
        var captured = new DateTimeOffset(2026, 8, 11, 8, 0, 0, TimeSpan.Zero).AddMilliseconds(sequence * 100);
        return new IoTestObservation(state, state ? "true" : "false", captured, captured.AddMilliseconds(-5), "Good", "BRCB", sequence, 1);
    }

    private static string FindRepoFile(string relativePath)
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);
        while (directory != null)
        {
            var candidate = Path.Combine(directory.FullName, relativePath);
            if (File.Exists(candidate))
                return candidate;
            directory = directory.Parent;
        }
        throw new FileNotFoundException($"Could not locate repository file '{relativePath}' from '{AppContext.BaseDirectory}'.");
    }
