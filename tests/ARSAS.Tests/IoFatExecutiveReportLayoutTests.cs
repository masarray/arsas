    public void ExecutivePdf_ReplacesUnknownSourceStateLabelsWithBooleanStates()
    {
        var project = BuildProject("REVIEW REQUIRED", "TBA", "N/A");

        var bytes = IoFatPdfReportService.Generate(project);
